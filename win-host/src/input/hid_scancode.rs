pub(super) fn scancode(hid: u32) -> Option<(u16, bool)> {
    // High byte 0xe0 marks the extended Set-1 sequence.
    const LETTERS: [u16; 26] = [
        0x1e, 0x30, 0x2e, 0x20, 0x12, 0x21, 0x22, 0x23, 0x17, 0x24, 0x25, 0x26, 0x32, 0x31, 0x18,
        0x19, 0x10, 0x13, 0x1f, 0x14, 0x16, 0x2f, 0x11, 0x2d, 0x15, 0x2c,
    ];
    const BASIC: [u16; 18] = [
        0x1c, 0x01, 0x0e, 0x0f, 0x39, 0x0c, 0x0d, 0x1a, 0x1b, 0x2b, 0x2b, 0x27, 0x28, 0x29, 0x33,
        0x34, 0x35, 0x3a,
    ];
    const NAV: [u16; 17] = [
        0xe037, 0x46, 0, 0xe052, 0xe047, 0xe049, 0xe053, 0xe04f, 0xe051, 0xe04d, 0xe04b, 0xe050,
        0xe048, 0x45, 0xe035, 0x37, 0x4a,
    ];
    const PAD: [u16; 15] = [
        0x4e, 0xe01c, 0x4f, 0x50, 0x51, 0x4b, 0x4c, 0x4d, 0x47, 0x48, 0x49, 0x52, 0x53, 0x56,
        0xe05d,
    ];
    const MODIFIERS: [u16; 8] = [0x1d, 0x2a, 0x38, 0xe05b, 0xe01d, 0x36, 0xe038, 0xe05c];
    let scan = match hid {
        0x04..=0x1d => LETTERS[(hid - 4) as usize],
        0x1e..=0x27 => (hid - 0x1e + 2) as u16,
        0x28..=0x39 => BASIC[(hid - 0x28) as usize],
        0x3a..=0x43 => (hid - 0x3a + 0x3b) as u16,
        0x44 => 0x57,
        0x45 => 0x58,
        0x46..=0x56 => NAV[(hid - 0x46) as usize],
        0x57..=0x65 => PAD[(hid - 0x57) as usize],
        0x66 => 0xe05e,
        0x67 => 0x59,
        0x68..=0x72 => (hid - 0x68 + 0x64) as u16,
        0x73 => 0x76,
        0x7f => 0xe020,
        0x80 => 0xe030,
        0x81 => 0xe02e,
        0x85 => 0x7e,
        0x87 => 0x73,
        0x88 => 0x70,
        0x89 => 0x7d,
        0x8a => 0x79,
        0x8b => 0x7b,
        0x8c => 0x5c,
        0x90 => 0x72,
        0x91 => 0x71,
        0x92 => 0x78,
        0x93 => 0x77,
        0xe0..=0xe7 => MODIFIERS[(hid - 0xe0) as usize],
        _ => return None,
    };
    if scan == 0 {
        None
    } else {
        Some((scan & 255, scan & 0xff00 == 0xe000))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn navigation_right_modifiers_and_keypad() {
        assert_eq!(scancode(0x04), Some((0x1e, false)));
        assert_eq!(scancode(0x52), Some((0x48, true)));
        assert_eq!(scancode(0xe4), Some((0x1d, true)));
        assert_eq!(scancode(0x58), Some((0x1c, true)));
        assert_eq!(scancode(0x60), Some((0x48, false)));
        assert_eq!(scancode(0xff), None);
    }
}
